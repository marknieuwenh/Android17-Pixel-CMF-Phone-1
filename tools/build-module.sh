#!/usr/bin/env bash
# Builds the flashable Magisk module zip.
#
#   tools/build-module.sh [--pixel-launcher NexusLauncherRelease.apk] [--stock DIR] [--out DIR]
#
# --pixel-launcher  Pixel Launcher APK to bundle. Take it from the same Android 17
#                   release as the GSI (see tools/get-pixel-launcher.sh). Without
#                   it the module only adds the device tuning, unless the GSI
#                   already contains Pixel Launcher.
# --stock           Output of tools/extract-stock.sh (default: ./stock if present).
# --out             Output directory (default: ./out).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
LAUNCHER_APK=""
STOCK=""
OUT="$ROOT/out"
NEXUS_PKG=com.google.android.apps.nexuslauncher
OVERLAY_NS=io.github.marknieuwenh.cmftetris

while [[ $# -gt 0 ]]; do
    case "$1" in
        --pixel-launcher) LAUNCHER_APK=$2; shift 2 ;;
        --stock) STOCK=$2; shift 2 ;;
        --out) OUT=$2; shift 2 ;;
        -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
        *) echo "!! Unknown argument $1" >&2; exit 1 ;;
    esac
done
[[ -z "$STOCK" && -d "$ROOT/stock" ]] && STOCK="$ROOT/stock"

# shellcheck source=tools/sdk.sh
source "$ROOT/tools/sdk.sh"
sdk_setup

BUILD="$OUT/build"
MOD="$BUILD/module"
rm -rf "$BUILD"
mkdir -p "$BUILD"
cp -r "$ROOT/module" "$MOD"
OVERLAY_DIR="$MOD/system/product/overlay"
mkdir -p "$OVERLAY_DIR"

# --- Signing key (kept between builds so updates keep the same signature) ---
KEYSTORE="$ROOT/.cache/keys/overlay.jks"
if [[ ! -f "$KEYSTORE" ]]; then
    mkdir -p "$(dirname "$KEYSTORE")"
    keytool -genkeypair -keystore "$KEYSTORE" -storepass android -keypass android \
        -alias overlay -keyalg RSA -keysize 2048 -validity 10000 \
        -dname "CN=CMF Phone 1 GSI overlays" >/dev/null 2>&1
fi

# build_overlay NAME TARGET PRIORITY RES_DIR
build_overlay() {
    local name=$1 target=$2 priority=$3 res=$4
    local work="$BUILD/overlays/$name"
    local pkg
    pkg="$OVERLAY_NS.$(echo "$name" | tr '[:upper:]' '[:lower:]')"
    mkdir -p "$work"
    cat > "$work/AndroidManifest.xml" <<EOF
<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="$pkg">
    <overlay android:targetPackage="$target" android:isStatic="true" android:priority="$priority"/>
    <application android:hasCode="false"/>
</manifest>
EOF
    "$AAPT2" compile --dir "$res" -o "$work/res.zip"
    "$AAPT2" link --manifest "$work/AndroidManifest.xml" -I "$ANDROID_JAR" \
        --min-sdk-version 37 --target-sdk-version 37 -o "$work/unsigned.apk" "$work/res.zip"
    mkdir -p "$OVERLAY_DIR/$name"
    java -jar "$APKSIGNER_JAR" sign --v4-signing-enabled false --ks "$KEYSTORE" --ks-pass pass:android \
        --out "$OVERLAY_DIR/$name/$name.apk" "$work/unsigned.apk" 2>/dev/null
    echo "   $name -> $target (priority $priority)"
}

echo ">> Building overlays"
for dir in "$ROOT"/overlays/*/; do
    name=$(basename "$dir")
    # shellcheck disable=SC1091
    target=$(. "$dir/overlay.conf"; echo "$target")
    # shellcheck disable=SC1091
    priority=$(. "$dir/overlay.conf"; echo "$priority")
    build_overlay "$name" "$target" "$priority" "$dir/res"
done

# --- Stock Nothing OS tuning -------------------------------------------------
if [[ -n "$STOCK" ]]; then
    echo ">> Carrying over stock tuning from $STOCK"
    python3 "$ROOT/tools/stock2overlay.py" --aapt2 "$AAPT2" --stock "$STOCK" \
        --rules "$ROOT/config/carry-over.conf" --out "$BUILD/stock-res"
    for tdir in "$BUILD"/stock-res/*/; do
        [[ -d "$tdir/res" ]] || continue
        target=$(basename "$tdir")
        case "$target" in
            android) name=TetrisStockFramework ;;
            com.android.systemui) name=TetrisStockSystemUI ;;
            *) name="TetrisStock_$(echo "$target" | tr '.' '_')" ;;
        esac
        build_overlay "$name" "$target" 900 "$tdir/res"
    done
    cp "$BUILD/stock-res/REPORT.md" "$MOD/stock-report.md"

    # Hardware features Nothing declared outside vendor. Features whose
    # software stack a GSI does not have are left out.
    if [[ -f "$STOCK/dumps/features.txt" ]]; then
        perm="$MOD/system/product/etc/permissions"
        mkdir -p "$perm"
        {
            echo '<?xml version="1.0" encoding="utf-8"?>'
            echo '<!-- Hardware features declared on stock Nothing OS (generated by build-module.sh) -->'
            echo '<permissions>'
            grep -E '^android\.hardware\.' "$STOCK/dumps/features.txt" \
                | grep -v -E '^android\.hardware\.(telephony\.ims|vulkan|opengles)' \
                | while IFS='=' read -r feature version; do
                    if [[ -n "$version" ]]; then
                        echo "    <feature name=\"$feature\" version=\"$version\"/>"
                    else
                        echo "    <feature name=\"$feature\"/>"
                    fi
                done
            echo '</permissions>'
        } > "$perm/cmf-tetris-hardware.xml"
        echo "   $(grep -c '<feature' "$perm/cmf-tetris-hardware.xml") hardware features declared"
    fi
else
    echo "!! No stock dump: building without Nothing OS tuning (run tools/extract-stock.sh on stock first)"
fi

# --- Pixel Launcher ------------------------------------------------------------
# Pixel Launcher uses hidden framework APIs for recents and gestures. Always
# shipped so a Pixel Launcher that comes with the GSI also gets it.
mkdir -p "$MOD/system/product/etc/sysconfig"
cat > "$MOD/system/product/etc/sysconfig/nexuslauncher-hiddenapi.xml" <<EOF
<?xml version="1.0" encoding="utf-8"?>
<config>
    <hidden-api-whitelisted-app package="$NEXUS_PKG"/>
</config>
EOF

if [[ -n "$LAUNCHER_APK" ]]; then
    echo ">> Bundling Pixel Launcher"
    badging=$("$AAPT2" dump badging "$LAUNCHER_APK")
    pkg=$(sed -n "s/^package: name='\([^']*\)'.*/\1/p" <<<"$badging")
    [[ "$pkg" == "$NEXUS_PKG" ]] || { echo "!! $LAUNCHER_APK is $pkg, not $NEXUS_PKG" >&2; exit 1; }
    version=$(sed -n "s/^package: .*versionName='\([^']*\)'.*/\1/p" <<<"$badging")
    platform=$(sed -n "s/^package: .*platformBuildVersionCode='\([^']*\)'.*/\1/p" <<<"$badging")
    echo "   version $version, built against API ${platform:-unknown}"
    if [[ -n "$platform" && "$platform" -lt 37 ]]; then
        echo "!! This Pixel Launcher is from an older Android release. It must match the GSI's" >&2
        echo "   Android version or recents and gestures will crash." >&2
        exit 1
    fi

    app="$MOD/system/product/priv-app/NexusLauncherRelease"
    mkdir -p "$app" "$MOD/system/product/etc/permissions"
    cp "$LAUNCHER_APK" "$app/NexusLauncherRelease.apk"

    # Grant every permission the APK asks for. Android refuses to boot when a
    # privileged app requests a privileged permission that is not listed here,
    # and listing non-privileged ones is harmless, so derive it from the APK.
    {
        echo '<?xml version="1.0" encoding="utf-8"?>'
        echo '<!-- Generated by build-module.sh from the bundled Pixel Launcher APK -->'
        echo '<permissions>'
        echo "    <privapp-permissions package=\"$NEXUS_PKG\">"
        sed -n "s/^uses-permission\(-sdk-23\)\{0,1\}: name='\([^']*\)'.*/\2/p" <<<"$badging" | sort -u \
            | sed 's/.*/        <permission name="&"\/>/'
        echo '    </privapp-permissions>'
        echo '</permissions>'
    } > "$MOD/system/product/etc/permissions/privapp-permissions-nexuslauncher.xml"
    echo "   $(grep -c '<permission ' "$MOD/system/product/etc/permissions/privapp-permissions-nexuslauncher.xml") permissions granted"

else
    echo ">> No --pixel-launcher given: module uses Pixel Launcher only if the GSI has it"
fi

# --- Package -------------------------------------------------------------------
VERSION=$(git -C "$ROOT" describe --tags --always --dirty 2>/dev/null || echo dev)
VERSION_CODE=$(git -C "$ROOT" rev-list --count HEAD 2>/dev/null || echo 1)
sed -i "s/@VERSION@/$VERSION/; s/@VERSION_CODE@/$VERSION_CODE/" "$MOD/module.prop"

suffix=""
[[ -n "$LAUNCHER_APK" ]] && suffix="-pixel-launcher"
[[ -z "$STOCK" ]] && suffix="$suffix-no-stock"
ZIP="$OUT/cmf-phone-1-gsi-tuning-$VERSION$suffix.zip"
rm -f "$ZIP"
(cd "$MOD" && zip -qr9 "$ZIP" .)
echo ">> Built $ZIP"
