#!/usr/bin/env python3
"""Turn the stock overlays saved by extract-stock.sh into overlay sources.

Reads stock/overlays/order.txt, dumps each APK with aapt2, keeps only the
values allowed by config/carry-over.conf and writes one Android resource tree
per target package:

    <out>/<target>/res/values[-qualifier]/stock.xml
    <out>/REPORT.md

When two stock overlays set the same value, the one later in order.txt
(higher priority on stock) wins, as it did on the phone.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

RESOURCE_RE = re.compile(r"^\s+resource 0x[0-9a-f]+ (\w+)/(\S+)")
VALUE_RE = re.compile(r"^\s+\(([^)]*)\) (.*)$")
DIMEN_RE = re.compile(r"^(-?\d+(?:\.\d+)?)(px|dp|dip|sp|pt|in|mm)$")
NUMBER_RE = re.compile(r"^-?\d+(?:\.\d+)?$")
INT_RE = re.compile(r"^-?\d+$")
QUOTED_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')
QUALIFIER_RE = re.compile(r"^[A-Za-z0-9+-]+$")


def load_rules(path):
    rules = []
    for line in Path(path).read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        target, types, regex = line.split(maxsplit=2)
        rules.append((target, set(types.split(",")), re.compile(regex)))
    return rules


def allowed(rules, target, rtype, name):
    return any(t == target and rtype in types and rx.match(name) for t, types, rx in rules)


def overlay_target(aapt2, apk):
    out = subprocess.run([aapt2, "dump", "badging", str(apk)],
                         capture_output=True, text=True).stdout
    m = re.search(r"^overlay: targetPackage='([^']+)'", out, re.M)
    return m.group(1) if m else None


def trim_number(text):
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text


def convert(rtype, raw):
    """Map one aapt2 dump value to (xml tag, attributes, body), or None to skip."""
    if raw.startswith(("@", "?")):
        return None  # references into the overlay's own package can't be carried
    if rtype == "bool" and raw in ("true", "false"):
        return ("bool", "", raw)
    if rtype == "integer":
        if INT_RE.match(raw):
            return ("integer", "", raw)
        if raw.startswith("0x"):
            return ("integer", "", str(int(raw, 16)))
        return None
    if rtype == "dimen":
        m = DIMEN_RE.match(raw)
        if m:
            unit = "dp" if m.group(2) == "dip" else m.group(2)
            return ("dimen", "", trim_number(m.group(1)) + unit)
        if NUMBER_RE.match(raw):
            return ("item", ' type="dimen" format="float"', raw)
        return None
    if rtype == "string":
        m = re.fullmatch(r'"(.*)"', raw)
        if not m:
            return None
        text = m.group(1).replace("\\", "\\\\").replace('"', '\\"')
        return ("string", ' translatable="false"', '"' + escape(text) + '"')
    return None


def convert_array(raw):
    body = raw.strip()
    if not (body.startswith("[") and body.endswith("]")):
        return None
    inner = body[1:-1].strip()
    if not inner:
        return ("integer-array", "", [])
    if inner.startswith('"'):
        items = QUOTED_RE.findall(inner)
        escaped = ['"' + escape(i) + '"' for i in items]
        return ("string-array", ' translatable="false"', escaped)
    items = [i.strip() for i in inner.split(",")]
    if not all(NUMBER_RE.match(i) for i in items):
        return None
    if all(INT_RE.match(i) for i in items):
        return ("integer-array", "", items)
    return ("array", "", items)


def parse_dump(text):
    """Yield (type, name, qualifier, raw value or ('array', raw))."""
    lines = text.splitlines()
    current = None
    i = 0
    while i < len(lines):
        line = lines[i]
        m = RESOURCE_RE.match(line)
        if m:
            current = (m.group(1), m.group(2))
        elif current:
            v = VALUE_RE.match(line)
            if v:
                qualifier, raw = v.group(1), v.group(2)
                if raw.startswith("(array)") and i + 1 < len(lines):
                    i += 1
                    yield current[0], current[1], qualifier, ("array", lines[i].strip())
                elif not raw.startswith("("):
                    yield current[0], current[1], qualifier, raw
        i += 1


def write_tree(out, target, values):
    by_qualifier = {}
    for (rtype, name, qualifier), (tag, attrs, body, source) in sorted(values.items()):
        by_qualifier.setdefault(qualifier, []).append((name, tag, attrs, body, source))
    for qualifier, entries in by_qualifier.items():
        folder = "values" + ("-" + qualifier if qualifier else "")
        d = out / target / "res" / folder
        d.mkdir(parents=True, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/stock2overlay.py from stock Nothing OS overlays. -->",
                 "<resources>"]
        for name, tag, attrs, body, source in entries:
            lines.append(f"    <!-- from {source} -->")
            if isinstance(body, list):
                lines.append(f'    <{tag} name="{name}"{attrs}>')
                lines += [f"        <item>{item}</item>" for item in body]
                lines.append(f"    </{tag}>")
            else:
                lines.append(f'    <{tag} name="{name}"{attrs}>{body}</{tag}>')
        lines.append("</resources>")
        (d / "stock.xml").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--aapt2", required=True)
    ap.add_argument("--stock", required=True, help="directory written by extract-stock.sh")
    ap.add_argument("--rules", required=True, help="config/carry-over.conf")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    rules = load_rules(args.rules)
    stock = Path(args.stock)
    out = Path(args.out)
    order = stock / "overlays" / "order.txt"
    if not order.exists():
        sys.exit(f"!! {order} not found, run tools/extract-stock.sh first")

    # target -> {(type, name, qualifier): (tag, attrs, body, source)}
    merged = {}
    skipped = []
    for line in order.read_text().splitlines():
        if not line.strip():
            continue
        pkg = line.split()[0]
        apk = stock / "overlays" / f"{pkg}.apk"
        target = overlay_target(args.aapt2, apk) if apk.exists() else None
        if not target:
            continue
        dump = subprocess.run([args.aapt2, "dump", "resources", str(apk)],
                              capture_output=True, text=True).stdout
        for rtype, name, qualifier, raw in parse_dump(dump):
            if not allowed(rules, target, rtype, name):
                continue
            if qualifier and not QUALIFIER_RE.match(qualifier):
                skipped.append((target, name, qualifier, "unsupported qualifier"))
                continue
            if isinstance(raw, tuple):
                conv = convert_array(raw[1])
            else:
                conv = convert(rtype, raw)
            if conv is None:
                skipped.append((target, name, qualifier, f"cannot carry value {raw!r}"))
                continue
            merged.setdefault(target, {})[(rtype, name, qualifier)] = (*conv, pkg)

    report = ["# Stock values carried over to the GSI", ""]
    for target, values in sorted(merged.items()):
        write_tree(out, target, values)
        report.append(f"## {target} ({len(values)} values)")
        report.append("")
        for (rtype, name, qualifier), (_, _, body, source) in sorted(values.items()):
            shown = ", ".join(body) if isinstance(body, list) else body
            q = f" ({qualifier})" if qualifier else ""
            report.append(f"- `{rtype}/{name}`{q} = `{shown}` from `{source}`")
        report.append("")
    if skipped:
        report += ["## Skipped", ""]
        report += [f"- `{t}` `{n}` ({q or 'default'}): {why}" for t, n, q, why in skipped]
        report.append("")
    out.mkdir(parents=True, exist_ok=True)
    (out / "REPORT.md").write_text("\n".join(report))
    total = sum(len(v) for v in merged.values())
    print(f">> Carried {total} stock values for {len(merged)} targets, skipped {len(skipped)}")


if __name__ == "__main__":
    main()
